    /**
     * Retrieves APPROVED uploads filtered by hostel, date (YYYY-MM-DD), and optional meal.
     * Ordered so they render seamlessly as a timeline (Ingredients -> Cooking -> Serving).
     */
    public List<Upload> findApprovedByFilters(int hostelId, String date, String meal) {
        List<Upload> list = new ArrayList<>();
        StringBuilder sql = new StringBuilder(
                "SELECT u.*, h.name as hostel_name, a.decided_at as approved_at, a.remark as approval_remark, " +
                "w.action as warden_action, w.remark as warden_remark, w.decided_at as warden_at " +
                "FROM uploads u " +
                "JOIN hostels h ON u.hostel_id = h.id " +
                "LEFT JOIN approvals a ON u.id = a.upload_id " +
                "LEFT JOIN warden_reviews w ON u.id = w.upload_id " +
                "WHERE u.hostel_id = ? AND u.status = 'APPROVED' "
        );

        if (date != null && !date.trim().isEmpty()) {
            sql.append("AND date(u.uploaded_at) = date(?) ");
        }
        if (meal != null && !meal.trim().isEmpty() && !meal.equalsIgnoreCase("ALL")) {
            sql.append("AND u.meal = ? ");
        }

        sql.append("ORDER BY u.dish_name ASC, " +
                   "CASE u.stage " +
                   "  WHEN 'Ingredients' THEN 1 " +
                   "  WHEN 'Cooking' THEN 2 " +
                   "  WHEN 'Serving' THEN 3 " +
                   "  ELSE 4 " +
                   "END ASC, u.uploaded_at ASC");

        try (Connection conn = DatabaseManager.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql.toString())) {
            int paramIndex = 1;
            ps.setInt(paramIndex++, hostelId);
            if (date != null && !date.trim().isEmpty()) {
                ps.setString(paramIndex++, date);
            }
            if (meal != null && !meal.trim().isEmpty() && !meal.equalsIgnoreCase("ALL")) {
                ps.setString(paramIndex++, meal);
            }

            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    Upload u = mapRow(rs);
                    u.setApprovedAt(rs.getString("approved_at"));
                    u.setRemark(rs.getString("approval_remark"));
                    u.setWardenAction(rs.getString("warden_action"));
                    u.setWardenRemark(rs.getString("warden_remark"));
                    u.setWardenAt(rs.getString("warden_at"));
                    list.add(u);
                }
            }
        } catch (SQLException e) {
            System.err.println("Error fetching approved uploads: " + e.getMessage());
        }
        return list;
    }

