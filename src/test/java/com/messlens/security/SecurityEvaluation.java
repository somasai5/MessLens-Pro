    static void e3Latency() {
        md.append("## E3. Cost of a policy decision (PDP)\n\n");
        AccessDecisionService pdp = AccessDecisionService.INSTANCE;
        User[] subjects = {
                new User(1, "w", "h", "s", Roles.WORKER, 1), new User(2, "h", "h", "s", Roles.HEAD, 1),
                new User(3, "wd", "h", "s", Roles.WARDEN, 1), new User(4, "s", "h", "s", Roles.STUDENT, null),
                new User(5, "a", "h", "s", Roles.ADMIN, null)};
        Action[] actions = Action.values();
        Random rnd = new Random(1);
        int n = 4_000_000;
        int pool = 4096;
        User[] su = new User[pool]; Action[] ac = new Action[pool]; Resource[] re = new Resource[pool];
        for (int i = 0; i < pool; i++) {
            su[i] = subjects[rnd.nextInt(subjects.length)];
            ac[i] = actions[rnd.nextInt(actions.length)];
            re[i] = Resource.of("x").hostelId(1 + rnd.nextInt(2)).owner(rnd.nextInt(8)).status(new String[]{"PENDING", "APPROVED", "REJECTED"}[rnd.nextInt(3)])
                    .decidedAt(Instant.now().minusSeconds(rnd.nextInt(10 * 86400))).targetRole(new String[]{"WORKER", "HEAD", "WARDEN"}[rnd.nextInt(3)]);
        }
        Instant now = Instant.now();
        int sink = 0;
        for (int i = 0; i < 1_000_000; i++) if (pdp.check(su[i & (pool - 1)], ac[i & (pool - 1)], re[i & (pool - 1)], now).permit) sink++;
        long t0 = System.nanoTime();
        for (int i = 0; i < n; i++) if (pdp.check(su[i & (pool - 1)], ac[i & (pool - 1)], re[i & (pool - 1)], now).permit) sink++;
        double meanNs = (System.nanoTime() - t0) / (double) n;

        long[] lat = new long[200_000];
        for (int i = 0; i < lat.length; i++) {
            long a = System.nanoTime();
            if (pdp.check(su[i & (pool - 1)], ac[i & (pool - 1)], re[i & (pool - 1)], now).permit) sink++;
            lat[i] = System.nanoTime() - a;
        }
        Arrays.sort(lat);
        md.append("| Decisions measured | Mean | Median | 99th percentile | Decisions per second (1 core) |\n|---:|---:|---:|---:|---:|\n| ")
          .append(n).append(" | ").append(String.format("%.0f ns", meanNs)).append(" | ").append(lat[lat.length / 2]).append(" ns | ")
          .append(lat[(int) (lat.length * 0.99)]).append(" ns | ").append(String.format("%,.0f", 1e9 / meanNs)).append(" |\n\n");
        md.append("A screen action costs a database query (hundreds of microseconds or more) and a PBKDF2 sign-in costs hundreds of milliseconds; the policy check is negligible next to either. (checksum ")
          .append(sink % 7).append(")\n\n");
    }

    static void e4Audit() throws Exception {
        md.append("## E4. Tamper-evident audit log (Schneier and Kelsey)\n\n");
        // throughput
        TestKit.freshEnvironment();
        int n = 5000;
        long t0 = System.nanoTime();
        for (int i = 0; i < n; i++) AuditLog.log(AuditEvent.anonymous("user" + i, "LOGIN_SUCCESS").detail("event " + i));
        double chainedUs = (System.nanoTime() - t0) / 1000.0 / n;

        try (Connection c = DatabaseManager.getConnection(); Statement s = c.createStatement()) {
            s.execute("CREATE TABLE plain_log (seq INTEGER PRIMARY KEY, ts TEXT, action TEXT, detail TEXT)");
        }
        t0 = System.nanoTime();
        for (int i = 0; i < n; i++) {
            try (Connection c = DatabaseManager.getConnection();
                 PreparedStatement ps = c.prepareStatement("INSERT INTO plain_log (seq, ts, action, detail) VALUES (?,?,?,?)")) {
                ps.setInt(1, i); ps.setString(2, Instant.now().toString()); ps.setString(3, "LOGIN_SUCCESS"); ps.setString(4, "event " + i);
                ps.executeUpdate();
            }
        }
        double plainUs = (System.nanoTime() - t0) / 1000.0 / n;

        t0 = System.nanoTime();
        var v = AuditLog.verify();
        double verifyMs = (System.nanoTime() - t0) / 1e6;
        md.append("| Entries | Append, plain table (no integrity) | Append, MAC chain + key evolution | Overhead per entry | Full verification of the chain |\n|---:|---:|---:|---:|---:|\n| ")
          .append(n).append(" | ").append(String.format("%.0f us", plainUs)).append(" | ").append(String.format("%.0f us", chainedUs)).append(" | ")
          .append(String.format("%.0f us", chainedUs - plainUs)).append(" | ").append(String.format("%.0f ms (%s)", verifyMs, v.ok ? "intact" : "FAILED")).append(" |\n\n");
        md.append("Each append here is its own auto-commit transaction including writing the key-state file; entries written inside an existing transaction (approvals, uploads) share its commit.\n\n");

        md.append("### Tamper detection\n\nLog of ").append(AuditChainTest.ENTRIES).append(" entries, ").append(AuditChainTest.TRIALS)
          .append(" randomised trials per attack, verifier key kept offline.\n\n| Attack | Detected |\n|---|---:|\n");
        int total = 0, found = 0;
        for (var e : AuditChainTest.attacks().entrySet()) {
            int d = AuditChainTest.detected(e.getValue(), AuditChainTest.TRIALS);
            total += AuditChainTest.TRIALS; found += d;
            md.append("| ").append(e.getKey()).append(" | ").append(d).append("/").append(AuditChainTest.TRIALS).append(" |\n");
        }
        md.append("| **All attacks** | **").append(found).append("/").append(total).append("** |\n\n");
        md.append("Not detected (by design, see limitations): an attacker who holds BOTH the database and the offline verifier key and rewrites the whole chain; deleting the log together with its key-state file and the verifier key.\n\n");
        TestKit.freshEnvironment(); // leave nothing behind
    }

    static void e5Passwords() {
        md.append("## E5. Password hashing cost (NIST SP 800-63B)\n\n");
        String salt = SecurityUtil.generateSalt();
        String pw = "correct horse battery staple";
        int rounds = 2_000_000;
        for (int i = 0; i < 200_000; i++) SecurityUtil.legacyHashPassword(pw, salt);
        long t0 = System.nanoTime();
        for (int i = 0; i < rounds; i++) SecurityUtil.legacyHashPassword(pw, salt);
        double shaUs = (System.nanoTime() - t0) / 1000.0 / rounds;

        SecurityUtil.hashPassword(pw, salt, 600_000);
        int k = 5;
        t0 = System.nanoTime();
        for (int i = 0; i < k; i++) SecurityUtil.hashPassword(pw, salt, 600_000);
        double pbkMs = (System.nanoTime() - t0) / 1e6 / k;

        double shaRate = 1e6 / shaUs, pbkRate = 1000.0 / pbkMs;
        md.append("| Scheme | Time per guess (1 core) | Guesses per second an attacker with a stolen database can try (1 core) |\n|---|---:|---:|\n");
        md.append("| Salted SHA-256 (old) | ").append(String.format("%.2f us", shaUs)).append(" | ").append(String.format("%,.0f", shaRate)).append(" |\n");
        md.append("| PBKDF2-HMAC-SHA256, 600,000 iterations (now) | ").append(String.format("%.0f ms", pbkMs)).append(" | ").append(String.format("%,.1f", pbkRate)).append(" |\n\n");
        md.append("Slow-down factor: about **").append(String.format("%,.0f", shaRate / pbkRate)).append("x** per guess. ")
          .append("A person signing in waits one hash (the figure above); an attacker testing a billion guesses pays it a billion times. ")
          .append("GPUs and ASICs are far faster than one CPU core for both schemes, so the ratio matters more than the absolute rate.\n\n");
        md.append("Blocklist: ").append(PasswordPolicy.blocklistSize()).append(" common passwords bundled. ")
          .append("Examples refused: `password123`, `Password1!`, `student123`, full-width Unicode variants.\n\n");
    }

    static void e6Lockout() {
        md.append("## E6. Effect of the sign-in lockout\n\n");
        long free = LoginThrottle.FREE_ATTEMPTS;
        long t = 0, day = 24L * 3600 * 1000;
        int attempts = 0;
        while (true) {
            attempts++;
            long lock = LoginThrottle.lockMillis(attempts);
            t += lock;               // the attacker must wait before the next try (guess itself assumed instant)
            if (t > day) { break; }
        }
        md.append("An attacker who guesses as fast as the lock allows can make **").append(attempts)
          .append(" guesses against one account in 24 hours** (first ").append(free).append(" are free, then locks of 1, 2, 4, 8, 16 minutes, capped at ")
          .append(LoginThrottle.MAX_LOCK_MINUTES).append(" minutes). Without a limit, a script making 1,000 attempts per second would make 86,400,000.\n\n")
          .append("The lock is stored in the database, so restarting the app does not reset it, and it also applies to usernames that do not exist (no account enumeration).\n\n");
    }
